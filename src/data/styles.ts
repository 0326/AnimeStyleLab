import { categories, categoryMap, type StyleCategory } from "./categories";

export type AnimeStyle = {
  id: string;
  slug: string;
  nameZh: string;
  nameEn: string;
  category: StyleCategory;
  summary: string;
  description: string;
  tags: string[];
  visualFeatures: string[];
  promptKeywords: string[];
  basePrompt: string;
  avoidPrompt: string;
  useCases: string[];
  recommendedRatios: string[];
  compatibleStyles: string[];
  similarStyles: string[];
  bestFor: string[];
  notRecommendedFor: string[];
  commonFailurePoints: string[];
  preview: {
    accent: string;
    glow: string;
    surface: string;
    label: string;
  };
  modelTips: {
    gptImage: string;
    nanoBanana: string;
  };
};

type StyleSeed = {
  slug: string;
  nameZh: string;
  nameEn: string;
  category: StyleCategory;
  summary: string;
  visualFeatures: string[];
  promptKeywords: string[];
  tags: string[];
  useCases: string[];
  recommendedRatios: string[];
  bestFor: string[];
  notRecommendedFor: string[];
  commonFailurePoints: string[];
  compatibleStyles: string[];
  similarStyles: string[];
  preview: AnimeStyle["preview"];
};

const byCategoryDescription = Object.fromEntries(
  categories.map((category) => [category.id, category.description]),
) as Record<StyleCategory, string>;

function createDescription(seed: StyleSeed) {
  const categoryText = byCategoryDescription[seed.category];
  return `${seed.nameZh} 强调 ${seed.visualFeatures.slice(0, 3).join("、")}。整体属于${categoryMap[seed.category].nameZh}路径，适合需要 ${seed.bestFor
    .slice(0, 2)
    .join("、")} 的画面。相比相近风格，它更突出 ${seed.tags
    .slice(0, 3)
    .join("、")}，在 PC 端风格库中能快速形成鲜明识别。${categoryText}`;
}

function createBasePrompt(seed: StyleSeed) {
  return [
    `${seed.nameEn.toLowerCase()} aesthetic`,
    ...seed.promptKeywords.slice(0, 6),
    "clean anime composition",
    "high detail illustration",
  ].join(", ");
}

function createAvoidPrompt(seed: StyleSeed) {
  return [
    "text",
    "watermark",
    "logo",
    "muddy rendering",
    ...seed.commonFailurePoints
      .map((item) =>
        item
          .replaceAll("画面", "")
          .replaceAll("角色", "")
          .replaceAll("主体", "")
          .trim(),
      )
      .slice(0, 3),
  ].join(", ");
}

function createModelTips(seed: StyleSeed) {
  return {
    gptImage: `用完整句子描述主体、镜头、氛围，并明确保留 ${seed.visualFeatures
      .slice(0, 2)
      .join(" 和 ")}。`,
    nanoBanana: `指令中优先写清 ${seed.useCases[0]} 的构图约束，再强调避免 ${seed.commonFailurePoints[0]}。`,
  };
}

function createStyle(seed: StyleSeed): AnimeStyle {
  return {
    id: seed.slug,
    slug: seed.slug,
    nameZh: seed.nameZh,
    nameEn: seed.nameEn,
    category: seed.category,
    summary: seed.summary,
    description: createDescription(seed),
    tags: seed.tags,
    visualFeatures: seed.visualFeatures,
    promptKeywords: seed.promptKeywords,
    basePrompt: createBasePrompt(seed),
    avoidPrompt: createAvoidPrompt(seed),
    useCases: seed.useCases,
    recommendedRatios: seed.recommendedRatios,
    compatibleStyles: seed.compatibleStyles,
    similarStyles: seed.similarStyles,
    bestFor: seed.bestFor,
    notRecommendedFor: seed.notRecommendedFor,
    commonFailurePoints: seed.commonFailurePoints,
    preview: seed.preview,
    modelTips: createModelTips(seed),
  };
}

